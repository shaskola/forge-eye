export const catalog: Record<Locale, { [K in keyof typeof en]: string }> = { en, es }

export type MsgKey = keyof typeof en
export type TranslateVars = Record<string, string | number>

export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'es'
}

export function parseLocale(value: unknown): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE
}

export function translate(locale: Locale, key: MsgKey, vars?: TranslateVars): string {
  let text = catalog[locale][key] ?? catalog.en[key] ?? key
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function translateKey(locale: Locale, key: string, vars?: TranslateVars, fallback = ''): string {
  if (key in catalog.en) return translate(locale, key as MsgKey, vars)
  return fallback || key
}
